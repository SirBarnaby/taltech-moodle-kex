import { chromium } from 'playwright';
import { installKex, login, LAB, iter3Seed } from '../test/harness/kex.ts';
const [,, theme='light', out='/tmp/kexwork/q'] = process.argv;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport:{width:1585,height:992} });
await login(ctx);
const p = await ctx.newPage();
p.on('pageerror', e=>console.log('pageerror', e.message));
p.on('console', m=>{ if(m.type()==='error') console.log('console.error', m.text().slice(0,200)); });
await installKex(p, iter3Seed({theme, debug:{freezeTime:7.3}}));
await p.goto(LAB+'/mod/quiz/attempt.php?attempt=1&cmid=155');
await p.waitForTimeout(2500);
await p.locator('input[type=radio]').first().check();
await p.screenshot({path: out+'_a1.png'});
await p.locator('input[value="Next page"]').click().catch(()=>p.getByRole('button',{name:'Next page'}).click());
await p.waitForTimeout(4000);
await p.screenshot({path: out+'_a2.png'});
console.log(await p.evaluate(()=>{const q=document.querySelectorAll('.qn_buttons a')[2]; const r=q.getBoundingClientRect(); const e=document.elementFromPoint(r.x+5,r.y+5); return JSON.stringify(r)+' '+e.tagName+'#'+e.id+'.'+e.className+' drawer '+JSON.stringify(document.querySelector('#theme_boost-drawers-blocks').getBoundingClientRect())})); await p.locator('.qn_buttons a').nth(2).click();
await p.waitForTimeout(1500);
await p.locator('.questionflag').first().click().catch(()=>{});
await p.getByRole('button',{name:/Finish attempt/}).click().catch(()=>p.locator('a:has-text("Finish attempt")').click());
await p.waitForTimeout(2500);
console.log(p.url());
await p.screenshot({path: out+'_summary.png'});
await p.getByRole('button',{name:'Submit all and finish'}).first().click();
await p.waitForTimeout(1200);
await p.locator('.modal-footer button:has-text("Submit all and finish"), [data-action=save]').first().click();
await p.waitForURL(/review\.php/);
await p.waitForTimeout(3000);
console.log(p.url());
await p.screenshot({path: out+'_review.png'});
await b.close();
