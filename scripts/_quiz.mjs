import { chromium } from 'playwright';
import { installKex, login, LAB, iter3Seed } from '../test/harness/kex.ts';
const [,, theme='light', out='/tmp/kexwork/q'] = process.argv;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport:{width:1585,height:992} });
await login(ctx);
const p = await ctx.newPage();
p.on('pageerror', e=>console.log('pageerror', e.message));
p.on('console', m=>{ if(m.type()==='error') console.log('console.error', m.text().slice(0,200)); });
await installKex(p, iter3Seed({theme, debug:{freezeTime:7.3}}));
await p.goto(LAB+'/mod/quiz/view.php?id=155');
await p.waitForTimeout(2000);
await p.locator('button:has-text("Attempt quiz"), button:has-text("Continue your attempt"), button:has-text("Re-attempt quiz")').first().click();
await p.waitForTimeout(1500);
const start = p.locator('.modal-footer button:has-text("Start attempt"), #id_submitbutton');
if (await start.count()) await start.first().click();
await p.waitForURL(/\/attempt\.php/);
await p.waitForTimeout(3000);
console.log(p.url());
await p.screenshot({path: out+'_attempt.png'});
console.log(await p.evaluate(()=>({kex: document.documentElement.dataset.kex, focus: document.documentElement.dataset.kexFocus, nav: !!document.querySelector('#mod_quiz_navblock'), timer: !!document.querySelector('#quiz-timer'), html: document.querySelector('#mod_quiz_navblock')?.outerHTML.replace(/\s+/g,' ').slice(0,1500)})));
await b.close();
